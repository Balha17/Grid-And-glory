#!/usr/bin/env bash
#
# prepare-android.sh — generate the Android project and apply every fix that
# `flutter create` does not do for a real-time networked, bilingual, store-bound game.
#
#   bash app/tools/prepare-android.sh
#   cd app && flutter pub get && flutter gen-l10n
#   flutter build apk --release --dart-define=WS_URL=wss://your-host/ws
#
# Idempotent: safe to re-run after `flutter create` wipes your edits.
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$APP_DIR"

ORG="gg.gridandglory"
APP_ID="gg.gridandglory.app"
PROJECT="grid_and_glory"

if ! command -v flutter >/dev/null 2>&1; then
  echo "error: flutter is not on PATH. Install the SDK first: https://docs.flutter.dev/get-started/install" >&2
  exit 1
fi

if [ ! -d android ]; then
  echo "==> generating android/ (flutter create)"
  cp pubspec.yaml /tmp/gg_pubspec.yaml
  cp analysis_options.yaml /tmp/gg_analysis.yaml
  flutter create --platforms=android --org "$ORG" --project-name "$PROJECT" .
  # flutter create scaffolds a demo widget test for a class named MyApp.
  # This app uses GridAndGloryApp, so remove the generated demo test (not project tests).
  rm -f test/widget_test.dart
  rmdir test 2>/dev/null || true
  cp /tmp/gg_pubspec.yaml pubspec.yaml
  cp /tmp/gg_analysis.yaml analysis_options.yaml
fi

echo "==> patching manifest, applicationId, app name, signing"
python3 - "$APP_DIR" "$APP_ID" <<'PY'
import pathlib
import re
import sys

app_dir = pathlib.Path(sys.argv[1])
app_id = sys.argv[2]

# --- 1. INTERNET permission in the RELEASE manifest -------------------------------
# flutter create only puts it in src/debug and src/profile. A release build without it
# installs fine and then cannot open a socket — the app looks broken and the reviewer
# cannot see why.
manifest = app_dir / "android" / "app" / "src" / "main" / "AndroidManifest.xml"
text = manifest.read_text()
if "android.permission.INTERNET" not in text:
    text = text.replace(
        "<application",
        '<uses-permission android:name="android.permission.INTERNET"/>\n\n    <application',
        1,
    )

# --- 2. Localised app name --------------------------------------------------------
if "@string/app_name" not in text:
    text = re.sub(r'android:label="[^"]*"', 'android:label="@string/app_name"', text, count=1)
manifest.write_text(text)

res_dir = app_dir / "android" / "app" / "src" / "main" / "res"
for locale, name in [("values", "Grid &amp; Glory"), ("values-ar", "التحدي الكروي")]:
    folder = res_dir / locale
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "strings.xml").write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n'
        f'<resources>\n    <string name="app_name">{name}</string>\n</resources>\n',
        encoding="utf-8",
    )

# --- 3. applicationId / namespace -------------------------------------------------
for gradle in list(app_dir.glob("android/app/build.gradle*")):
    s = gradle.read_text()
    s = re.sub(r'namespace\s*[= ]\s*"[^"]*"', f'namespace = "{app_id}"', s)
    s = re.sub(r'applicationId\s*[= ]\s*"[^"]*"', f'applicationId = "{app_id}"', s)

    # --- 4. Release signing, wired to android/key.properties ----------------------
    # Without this the release build is signed with the throwaway debug key: it
    # installs, but Play rejects it and no future update can use the same identity.
    #
    # ORDERING MATTERS. Gradle's Kotlin DSL allows only imports before `plugins {}`;
    # a top-level `val` there is a hard build failure. So the imports go at the very
    # top and the property loading goes immediately before `android {`.
    if "// gg:signing" not in s:
        s = "import java.util.Properties\nimport java.io.FileInputStream\n\n" + s

        prologue = (
            "// gg:signing — generated by app/tools/prepare-android.sh\n"
            "val keystoreProperties = Properties()\n"
            "val keystorePropertiesFile = rootProject.file(\"key.properties\")\n"
            "val hasReleaseKey = keystorePropertiesFile.exists()\n"
            "if (hasReleaseKey) {\n"
            "    keystoreProperties.load(FileInputStream(keystorePropertiesFile))\n"
            "}\n\n"
            "android {\n"
            "    signingConfigs {\n"
            "        create(\"release\") {\n"
            "            keyAlias = keystoreProperties[\"keyAlias\"] as String?\n"
            "            keyPassword = keystoreProperties[\"keyPassword\"] as String?\n"
            "            storeFile = (keystoreProperties[\"storeFile\"] as String?)?.let { file(it) }\n"
            "            storePassword = keystoreProperties[\"storePassword\"] as String?\n"
            "        }\n"
            "    }\n"
        )
        s = s.replace("android {", prologue, 1)

        # Falls back to debug signing when no key exists, so CI without secrets still builds.
        s = s.replace(
            "signingConfig = signingConfigs.getByName(\"debug\")",
            "signingConfig = if (hasReleaseKey) signingConfigs.getByName(\"release\") "
            "else signingConfigs.getByName(\"debug\")",
        )

    gradle.write_text(s)

# --- 5. Keep the Android launcher class package aligned with namespace/applicationId --
# flutter create derives MainActivity's Kotlin package from ORG + PROJECT. The
# applicationId above is intentionally different, so rewrite the package declaration
# and place the source under the matching Kotlin directory. Otherwise Android can try
# to launch gg.gridandglory.app.MainActivity while the APK contains a different class,
# causing an immediate crash before Flutter/Dart starts.
main_activity = next((app_dir / "android" / "app" / "src" / "main" / "kotlin").rglob("MainActivity.kt"), None)
if main_activity is None:
    raise SystemExit("error: flutter create did not generate MainActivity.kt")
source = main_activity.read_text(encoding="utf-8")
source, replacements = re.subn(
    r"(?m)^package\s+[A-Za-z_][A-Za-z0-9_.]*",
    f"package {app_id}",
    source,
    count=1,
)
if replacements != 1:
    raise SystemExit("error: could not find MainActivity Kotlin package declaration")
main_activity.write_text(source, encoding="utf-8")
expected_dir = app_dir / "android" / "app" / "src" / "main" / "kotlin" / pathlib.Path(*app_id.split("."))
expected_dir.mkdir(parents=True, exist_ok=True)
expected_file = expected_dir / "MainActivity.kt"
if main_activity != expected_file:
    expected_file.write_text(source, encoding="utf-8")
    main_activity.unlink()

# --- 6. Cleartext is allowed in DEBUG ONLY ----------------------------------------

debug_manifest = app_dir / "android" / "app" / "src" / "debug" / "AndroidManifest.xml"
debug_manifest.parent.mkdir(parents=True, exist_ok=True)
if not debug_manifest.exists() or "usesCleartextTraffic" not in debug_manifest.read_text():
    debug_manifest.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<manifest xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <uses-permission android:name="android.permission.INTERNET"/>\n'
        '    <!-- debug only: lets the emulator reach ws://10.0.2.2:8080 -->\n'
        '    <application android:usesCleartextTraffic="true" />\n'
        '</manifest>\n'
    )

key_props = app_dir / "android" / "key.properties"
print(f"    applicationId -> {app_id}")
print(f"    release signing -> {'key.properties found' if key_props.exists() else 'no key (debug signing)'}")
PY

echo "==> done. Next:"
echo "    cd app && flutter pub get && flutter gen-l10n"
echo "    flutter build apk --release --dart-define=WS_URL=wss://<host>/ws"
