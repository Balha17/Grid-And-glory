#!/usr/bin/env bash
#
# keystore.sh — create the release signing key for the Play Store.
#
# Run ONCE. Back up the .jks and the passwords somewhere you will still have them in
# five years: losing this key means you can never update the app under the same listing.
#
#   bash app/tools/keystore.sh
#
# Then:flutter build appbundle --release
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ANDROID_DIR="$APP_DIR/android"
KEYSTORE="$ANDROID_DIR/upload-keystore.jks"
PROPS="$ANDROID_DIR/key.properties"
ALIAS="upload"

if [ ! -d "$ANDROID_DIR" ]; then
  echo "error: run app/tools/prepare-android.sh first (it creates android/)" >&2
  exit 1
fi

if [ -f "$KEYSTORE" ]; then
  echo "refusing to overwrite an existing keystore: $KEYSTORE" >&2
  echo "If you really want a new one, move it away first — but understand that the" >&2
  echo "old key can never sign an update to the same Play listing again." >&2
  exit 1
fi

if ! command -v keytool >/dev/null 2>&1; then
  echo "error: keytool not found. It ships with the JDK (JAVA_HOME/bin)." >&2
  exit 1
fi

STORE_PASS="${KEYSTORE_PASSWORD:-$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)}"
KEY_PASS="${KEY_PASSWORD:-$STORE_PASS}"

keytool -genkeypair -v \
  -keystore "$KEYSTORE" \
  -storetype JKS \
  -keyalg RSA \
  -keysize 2048 \
  -validity 10000 \
  -alias "$ALIAS" \
  -storepass "$STORE_PASS" \
  -keypass "$KEY_PASS" \
  -dname "CN=Grid & Glory, OU=Mobile, O=Grid and Glory, L=Tunis, C=TN"

cat > "$PROPS" <<EOF
# Generated by app/tools/keystore.sh — NEVER commit this file.
storePassword=$STORE_PASS
keyPassword=$KEY_PASS
keyAlias=$ALIAS
storeFile=upload-keystore.jks
EOF

chmod 600 "$PROPS" "$KEYSTORE"

echo
echo "wrote $KEYSTORE"
echo "wrote $PROPS"
echo
echo "Add these to the Play Console (and to Firebase if you use it):"
keytool -list -v -keystore "$KEYSTORE" -alias "$ALIAS" -storepass "$STORE_PASS" \
  | grep -E "SHA1:|SHA256:" | sed 's/^/  /'
echo
echo "BACK THESE UP NOW: $KEYSTORE and the passwords in $PROPS"
echo
echo "Next: cd app && flutter build appbundle --release --dart-define=WS_URL=wss://<host>/ws"
